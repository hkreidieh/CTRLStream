/**
 * Generates src/prompts.generated.ts from plugin/skills/<name>/SKILL.md so the MCP prompts (for Claude
 * Desktop users who get the .mcpb without the plugin's skills) and the skills have one source of
 * truth. Run by `pnpm build` (prebuild) and `pnpm gen:prompts`; the output is committed.
 *
 * Plain Node (22.18+ strips TypeScript types natively); no dependencies.
 *
 * Adjustments made to the text, nothing else:
 *  - YAML front matter is removed; its description becomes the prompt description.
 *  - `${CLAUDE_PLUGIN_ROOT}/knowledge/<file>.json` becomes a pointer to the `knowledge` tool, because
 *    a Desktop client has no plugin directory to read.
 *  - A one-paragraph preamble says the text arrives as a prompt and how to reach the other guides.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const NAMES = ['setup', 'troubleshoot', 'platforms'] as const;
const TITLES: Record<string, string> = {
  setup: 'Set up OBS for streaming',
  troubleshoot: 'Fix OBS when it is broken',
  platforms: 'Platform rules: bitrate, resolution, encoder',
};

interface Out {
  name: string;
  title: string;
  description: string;
  text: string;
  source: string;
  sourceSha256: string | null;
}

function frontMatter(md: string): { meta: Record<string, string>; body: string } {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(md);
  if (!m) return { meta: {}, body: md };
  const meta: Record<string, string> = {};
  for (const line of m[1]!.split(/\r?\n/)) {
    const i = line.indexOf(':');
    if (i > 0) meta[line.slice(0, i).trim()] = line.slice(i + 1).trim().replace(/^["']|["']$/g, '');
  }
  return { meta, body: md.slice(m[0].length) };
}

function adapt(body: string): string {
  return body
    .replace(/`?\$\{CLAUDE_PLUGIN_ROOT\}\/knowledge\/([a-z-]+)\.json`?/g, (_m, f: string) => `the ${f} table (call the \`knowledge\` tool with file "${f}")`)
    .replace(/`?\$\{CLAUDE_PLUGIN_ROOT\}\/knowledge\/`?/g, 'the knowledge tables (the `knowledge` tool)');
}

const PREAMBLE =
  'You are using CTRLStream through MCP prompts. Where this guide says "skill", the same guide is available as the MCP prompt of that name (setup, troubleshoot, platforms); if your client cannot load prompts, call the `get_started` tool. Knowledge tables are read with the `knowledge` tool.\n\n';

const out: Out[] = [];
const missing: string[] = [];
for (const name of NAMES) {
  const file = path.join(root, 'plugin', 'skills', name, 'SKILL.md');
  if (!existsSync(file)) {
    missing.push(name);
    out.push({ name, title: TITLES[name]!, description: `The ${name} guide was not found when this build was made.`, text: `The ${name} guide (plugin/skills/${name}/SKILL.md) was missing at build time. Use the tool descriptions, starting with obs_status.`, source: `plugin/skills/${name}/SKILL.md`, sourceSha256: null });
    continue;
  }
  const md = readFileSync(file, 'utf8');
  const { meta, body } = frontMatter(md);
  out.push({
    name,
    title: TITLES[name]!,
    description: meta['description'] ?? TITLES[name]!,
    text: PREAMBLE + adapt(body).trim() + '\n',
    source: `plugin/skills/${name}/SKILL.md`,
    sourceSha256: createHash('sha256').update(md).digest('hex'),
  });
}

const ts = `// GENERATED by scripts/gen-prompts.ts from plugin/skills/*/SKILL.md. Do not edit; run \`pnpm gen:prompts\`.
/* eslint-disable */

export interface GeneratedPrompt {
  name: string;
  title: string;
  description: string;
  text: string;
  source: string;
  sourceSha256: string | null;
}

export const PROMPTS: GeneratedPrompt[] = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(path.join(root, 'src', 'prompts.generated.ts'), ts);
process.stdout.write(`gen-prompts: wrote ${out.length} prompts${missing.length ? ` (missing: ${missing.join(', ')})` : ''}\n`);
